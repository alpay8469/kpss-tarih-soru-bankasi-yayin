import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import {loadContent} from './content.mjs';
import {createHash} from 'node:crypto';
const root = fileURLToPath(new URL('..', import.meta.url));
const bank = await loadContent();
const questions = bank.questions;
if (!questions.length || new Set(questions.map(q => q.id)).size !== questions.length) throw new Error('Pilot bankası boş veya yinelenen soru kimliği var.');
const clean = questions.map(q => ({ id: q.id, revision: q.revision || 1, topic: q.topic, subtopic:q.subtopic||null, skill: q.skill, stem: q.stem,
  ...(['Kolay','Orta','Zor'].includes(q.difficulty)?{difficulty:q.difficulty}:{}),
  options: q.options, answer: q.answer,
  explanation: q.explanation,
  sources: q.sources.map(id => bank.sources[id]).filter(Boolean) }));
for (const q of clean) if(q.options.length !== 5 || !'ABCDE'.includes(q.answer)) throw new Error(q.id);
const navigation = await readFile(path.join(root,'src/navigation.js'),'utf8');
const resultReview = await readFile(path.join(root,'src/result-review.js'),'utf8');
const requestJSON = await readFile(path.join(root,'src/request-json.js'),'utf8');
const answerSave = await readFile(path.join(root,'src/answer-save.js'),'utf8');
const studySummaryServer = await readFile(path.join(root,'src/study-summary-server.js'),'utf8');
const studySummaryUI = await readFile(path.join(root,'src/study-summary-ui.js'),'utf8');
const reportsUI = await readFile(path.join(root,'src/reports-ui.js'),'utf8');
const html = (await readFile(path.join(root,'src/index.html'),'utf8'))
  .replace('__BANK_TOTAL__',String(clean.length))
  .replace('/* REQUEST_JSON */',()=>requestJSON)
  .replace('/* ANSWER_SAVE */',()=>answerSave)
  .replace('/* STUDY_SUMMARY */',()=>studySummaryUI)
  .replace('/* RESULT_REVIEW */',()=>resultReview)
  .replace('/* REPORTS */',()=>reportsUI)
  .replace('/* NAVIGATION */',()=>navigation).replace(/\r\n?/g,'\n');
const admin = (await readFile(path.join(root,'src/admin.html'),'utf8')).replace('/* REQUEST_JSON */',()=>requestJSON).replace('/* SHARED_STYLE */',()=>html.match(/<style>([\s\S]*?)<\/style>/)[1]).replace(/\r\n?/g,'\n');
const server = await readFile(path.join(root,'src/server.js'),'utf8');
const security = await readFile(path.join(root,'src/security.js'),'utf8');
const ownerAccess = await readFile(path.join(root,'src/owner-access.js'),'utf8');
const scriptHashes = page => [...page.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m=>createHash('sha256').update(m[1]).digest('base64'));
const reportsServer = await readFile(path.join(root,'src/reports-server.js'),'utf8');
// Immutable fallback for tests created before per-test question snapshots existed.
const legacy = JSON.parse(await readFile(path.join(root,'src/legacy-bank-2026-09-28.json'),'utf8'));
const output = `// Generated by scripts/build.mjs. Edit src/ instead.\nconst PAGE = ${JSON.stringify(html)};\nconst ADMIN_PAGE = ${JSON.stringify(admin)};\nconst PAGE_SCRIPT_HASHES = ${JSON.stringify(scriptHashes(html))};\nconst ADMIN_SCRIPT_HASHES = ${JSON.stringify(scriptHashes(admin))};\nconst BANK = ${JSON.stringify(clean)};\nconst LEGACY_BANK = ${JSON.stringify(legacy)};\n${reportsServer}\n${security}\n${ownerAccess}\n${studySummaryServer}\n${server}`;
await mkdir(path.join(root,'worker'),{recursive:true});
await mkdir(path.join(root,'dist/server'),{recursive:true});
await writeFile(path.join(root,'worker/index.js'), output);
await writeFile(path.join(root,'dist/server/index.js'),output);
console.log(`Hazır: ${clean.length} soru, tek Worker dosyası.`);

